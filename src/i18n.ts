const KEY = "ln.lang";

export function storedLang(): Lang {
  return localStorage.getItem(KEY) === "he" ? "he" : "en";
}

export function storeLang(l: Lang) {
  localStorage.setItem(KEY, l);
}

export type Strings = (typeof STRINGS)[Lang];
